function toPeriods(prices) {
  const dates = Object.keys(prices).sort()
  if (!dates.length) return []
  const periods = []
  let from = dates[0], to = dates[0], price = prices[dates[0]]
  for (let i = 1; i < dates.length; i++) {
    const d = dates[i], p = prices[d]
    const prev = new Date(to + 'T00:00:00')
    const curr = new Date(d + 'T00:00:00')
    const gap = Math.round((curr - prev) / 86400000)
    if (gap === 1 && p === price) { to = d }
    else { periods.push({ from, to, price }); from = d; to = d; price = p }
  }
  periods.push({ from, to, price })
  return periods
}

